// Builds backend/src/lib/contestBank.js — the questions the server can use for contests and battles —
// from the app's game banks. Answers must stay on the server, so it needs its own copy.
// Question types: story/book facts (multiple choice), famous "who said it" (character identification),
// complete-the-verse (fill-in-the-gap / scripture memory) and "which happened first/last" (chronology).
// Run after regenerating the game banks:  node scripts/gen_contest_bank.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (n) => JSON.parse(readFileSync(path.join(root, 'src/data/games', n), 'utf8'));
const every = (list, n) => list.filter((_, i) => i % n === 0); // a stable, even sample

const bank = [];
const trivia = read('trivia.json');
for (const x of trivia) {
  if (x.k === 'story' || x.k === 'books') bank.push({ id: x.id, c: x.c, q: x.q, o: x.o, a: x.a, r: x.r });
}
for (const x of every(trivia.filter((t) => t.k === 'verse'), 5)) bank.push({ id: x.id, c: 'verses', q: x.q, o: x.o, a: x.a, r: x.r });
for (const x of read('who.json')) {
  if (x.k === 'famous') bank.push({ id: x.id, c: 'who', q: `Who said: “${x.q}”`, o: x.o, a: x.a, r: x.r });
}
for (const x of every(read('chronology.json'), 6)) bank.push({ id: x.id, c: 'chronology', q: x.q, o: x.o, a: x.a, r: x.r });

const out = `// GENERATED by scripts/gen_contest_bank.mjs — do not edit by hand.
export const CONTEST_BANK = ${JSON.stringify(bank)};
`;
writeFileSync(path.join(root, 'backend/src/lib/contestBank.js'), out);
const counts = {}; for (const b of bank) counts[b.c] = (counts[b.c] || 0) + 1;
console.log(`${bank.length} questions, ${Math.round(out.length / 1024)} KB`, counts);
